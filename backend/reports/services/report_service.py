"""Report orchestration: create, dispatch background generation, list.

Reports are generated on a daemon thread of the process that created them
(web or Celery worker). A process restart kills that thread and would leave
the report "generating" forever, with the UI polling it. Liveness is
therefore explicit: the generating thread holds a Postgres session-level
advisory lock for its report (released by the database itself when the
connection dies), and :func:`reap_dead_reports` fails pending/generating
reports past a short grace period whose lock nobody holds. It runs on its
own, throttled, whenever reports are listed or opened, so no manual action
is needed; it can never fail a report a live thread is still generating,
and a generator never overwrites a report that was failed meanwhile.
"""

from __future__ import annotations

import logging
import threading
import time
import uuid
from datetime import timedelta
from typing import Any

from django.db import connection
from django.db import transaction
from django.db.models import F
from django.utils import timezone

from backend.common.threading import dispatch_in_thread
from backend.reports.models import Report

from .generators import GENERATORS
from .generators import RULE_KEYS

logger = logging.getLogger(__name__)

_IN_FLIGHT = (Report.Status.PENDING, Report.Status.GENERATING)
# First key of every report liveness lock ("RPRT"); the second is per report.
LOCK_NAMESPACE = 0x52505254
# A report younger than this is never reaped: covers dispatch -> thread start.
DEAD_GRACE_SECONDS = 120
# Opportunistic reaping runs at most this often per process.
REAP_INTERVAL_SECONDS = 60
# ``ordering`` values of the report list -> ORDER BY (``id`` breaks ties;
# unfinished reports have no completed_at and sort last either way).
LIST_ORDERINGS: dict[str, tuple[Any, ...]] = {
    "created_at": ("created_at", "id"),
    "-created_at": ("-created_at", "-id"),
    "completed_at": (F("completed_at").asc(nulls_last=True), "id"),
    "-completed_at": (F("completed_at").desc(nulls_last=True), "-id"),
    "title": ("title", "-created_at", "id"),
    "-title": ("-title", "-created_at", "id"),
    "report_type": ("report_type", "-created_at", "id"),
    "-report_type": ("-report_type", "-created_at", "id"),
    "status": ("status", "-created_at", "id"),
    "-status": ("-status", "-created_at", "id"),
}
DEFAULT_LIST_ORDERING = "-created_at"
_TITLE_MAX = 500
_DEAD_MESSAGE = (
    "Report generation stopped before it finished: the process generating it exited "
    "(restart or deploy). Generate the report again."
)

# Non-Postgres databases (never in production): an in-process stand-in.
_local_lock = threading.Lock()
_local_live: set[int] = set()
_last_reap = 0.0


def _lock_key(report_id: Any) -> int:
    """A non-negative int4 derived from the report's UUID (second advisory-lock key)."""
    return uuid.UUID(str(report_id)).int & 0x7FFFFFFF


def _hold_liveness_lock(report_id: Any) -> None:
    """Mark *report_id* as being generated by this thread's DB session."""
    key = _lock_key(report_id)
    if connection.vendor != "postgresql":
        with _local_lock:
            _local_live.add(key)
        return
    with connection.cursor() as cursor:
        cursor.execute("SELECT pg_try_advisory_lock(%s, %s)", [LOCK_NAMESPACE, key])


def _release_liveness_lock(report_id: Any) -> None:
    key = _lock_key(report_id)
    if connection.vendor != "postgresql":
        with _local_lock:
            _local_live.discard(key)
        return
    try:
        with connection.cursor() as cursor:
            cursor.execute("SELECT pg_advisory_unlock(%s, %s)", [LOCK_NAMESPACE, key])
    except Exception:  # noqa: BLE001 - the connection is closed next, which releases it anyway
        logger.debug("Releasing the liveness lock of report %s failed", report_id, exc_info=True)


def _live_keys(keys: set[int]) -> set[int]:
    """Which of *keys* a live session (any process) currently holds (read-only)."""
    if not keys:
        return set()
    if connection.vendor != "postgresql":
        with _local_lock:
            return keys & _local_live
    with connection.cursor() as cursor:
        # Two-key advisory locks appear as classid = key1, objid = key2, objsubid = 2.
        cursor.execute(
            "SELECT DISTINCT objid FROM pg_locks WHERE locktype = 'advisory' AND granted "
            "AND database = (SELECT oid FROM pg_database WHERE datname = current_database()) "
            "AND objsubid = 2 AND classid = %s AND objid::int8 = ANY(%s::int8[])",
            [LOCK_NAMESPACE, sorted(keys)],
        )
        return {int(row[0]) for row in cursor.fetchall()}


def is_generating_live(report_id: Any) -> bool:
    """True while some process's thread is generating *report_id*."""
    key = _lock_key(report_id)
    return key in _live_keys({key})


def create_and_dispatch(
    *,
    report_type: str,
    config: dict[str, Any],
    title: str | None = None,
    description: str = "",
    user=None,
    expires_in_days: int | None = 30,
) -> Report:
    """Create a Report row, then run the generator in a daemon thread."""

    if report_type not in GENERATORS:
        msg = f"Unknown report_type: {report_type}"
        raise ValueError(msg)
    _validate_config(report_type, config)

    final_title = title or _default_title(report_type, config, user=user)
    expires_at = timezone.now() + timedelta(days=int(expires_in_days)) if expires_in_days else None

    report = Report.objects.create(
        report_type=report_type,
        title=final_title,
        description=description,
        config=config,
        created_by=user if (user and user.is_authenticated) else None,
        expires_at=expires_at,
    )
    _dispatch(report.id)
    return report


def _dispatch(report_id) -> None:
    dispatch_in_thread(_run_generation, report_id, name=f"report-{report_id}")


def _run_generation(report_id) -> None:
    try:
        # Held for the whole generation on this thread's DB session; the
        # database drops it if the process dies (see module docstring).
        _hold_liveness_lock(report_id)
        with transaction.atomic():
            report = Report.objects.select_for_update().get(id=report_id)
            if report.status != Report.Status.PENDING:
                return
            report.mark_generating()
        _generate(report)
    except Report.DoesNotExist:
        logger.warning("Report %s vanished before generation", report_id)
    except Exception as exc:
        logger.exception("Report generation failed for %s", report_id)
        Report.objects.filter(id=report_id, status__in=_IN_FLIGHT).update(
            status=Report.Status.FAILED,
            error_message=str(exc)[:5000],
            completed_at=timezone.now(),
        )
    finally:
        _release_liveness_lock(report_id)
        connection.close()


def _generate(report: Report) -> None:
    generator = GENERATORS[report.report_type]
    # Generators read only the requesting user's data (staff: everything).
    data = generator(report.config or {}, user=report.created_by)
    summary = _make_summary(report.report_type, data)
    now = timezone.now()
    # Only a report still in flight is completed: one that was failed (or
    # deleted) meanwhile is never flipped back to COMPLETED.
    updated = Report.objects.filter(id=report.id, status__in=_IN_FLIGHT).update(
        report_data=data,
        summary=summary,
        status=Report.Status.COMPLETED,
        completed_at=now,
        progress_percent=100,
        error_message="",
    )
    if not updated:
        logger.warning("Report %s is no longer in flight; its generated data was dropped", report.id)
        return
    report.report_data = data
    report.summary = summary
    report.status = Report.Status.COMPLETED
    report.completed_at = now
    report.progress_percent = 100
    report.error_message = ""


def _validate_config(report_type: str, config: dict[str, Any]) -> None:
    """Synchronously check required config keys before background dispatch."""

    required: dict[str, list[str]] = {
        "model_analysis": ["model_id"],
        "template_comparison": ["template_slug"],
        "experiment_report": ["experiment_id"],
    }
    config = config or {}
    for key in required.get(report_type, []):
        if not config.get(key):
            # model_analysis historically also accepted model_slug.
            if key == "model_id" and config.get("model_slug"):
                continue
            msg = f"Missing required config key for {report_type}: {key}"
            raise ValueError(msg)
    plan_hash = config.get("plan_hash")
    if plan_hash is not None and not (isinstance(plan_hash, str) and len(plan_hash) == 64):
        msg = "plan_hash must be a 64-character analysis plan hash"
        raise ValueError(msg)
    for key in RULE_KEYS:
        if key in config and not isinstance(config[key], bool):
            msg = f"{key} must be a boolean"
            raise ValueError(msg)


def _experiment_name(experiment_id: Any, user=None) -> str | None:
    """The name of an experiment *user* may report on (staff: any); None when unknown."""
    from django.core.exceptions import ValidationError

    from backend.generation.models import Experiment

    from .generators import _owned

    if not experiment_id:
        return None
    try:
        name = _owned(Experiment.objects.all(), user).filter(id=experiment_id).values_list("name", flat=True).first()
    except (ValidationError, ValueError, TypeError):
        # A malformed id is reported by the generator (failed report), not here.
        return None
    return str(name) if name else None


def _default_title(report_type: str, config: dict[str, Any], *, user=None) -> str:  # noqa: PLR0911 - one branch per type
    if report_type == "model_analysis":
        slug = config.get("model_id") or config.get("model_slug", "?")
        return f"Model analysis: {slug}"
    if report_type == "template_comparison":
        return f"Template comparison: {config.get('template_slug', '?')}"
    if report_type == "tool_analysis":
        return f"Tool analysis: {config.get('tool_name') or 'all tools'}"
    if report_type == "generation_analytics":
        return f"Generation analytics ({config.get('days', 7)}d)"
    if report_type == "comprehensive":
        return f"Comprehensive report ({config.get('days', 30)}d)"
    if report_type == "experiment_report":
        # Named after the experiment (the id says nothing in a report list).
        name = _experiment_name(config.get("experiment_id"), user)
        return f"Experiment report: {name or config.get('experiment_id', '?')}"[:_TITLE_MAX]
    return "Report"


def _make_summary(report_type: str, data: dict[str, Any]) -> dict[str, Any]:  # noqa: PLR0911 - one branch per type
    """Compact denormalized summary for list rendering."""

    coverage = data.get("analysis_coverage") or {}
    analysis = {
        "plan_hash": coverage.get("plan_hash"),
        "plan_rule": coverage.get("plan_rule"),
        "measured_jobs": coverage.get("measured"),
        "mixed_plans": coverage.get("mixed_plans"),
    }
    if report_type == "model_analysis":
        gen = data.get("generation", {})
        return {
            "model_id": (data.get("model") or {}).get("model_id"),
            "total_jobs": gen.get("total_jobs", 0),
            "success_rate": gen.get("success_rate"),
            "total_findings": data.get("total_findings"),
            "total_loc": (data.get("loc") or {}).get("measured_loc"),
            **analysis,
        }
    if report_type == "template_comparison":
        return {
            "template_slug": (data.get("template") or {}).get("slug"),
            "model_count": data.get("total_models", 0),
            **analysis,
        }
    if report_type == "experiment_report":
        return {
            "experiment_id": (data.get("experiment") or {}).get("id"),
            "experiment_name": (data.get("experiment") or {}).get("name"),
            "condition_count": data.get("total_conditions", 0),
            **analysis,
        }
    if report_type == "tool_analysis":
        return {
            "tool": data.get("tool_filter"),
            "total_findings": data.get("total_findings", 0),
            "tool_count": len(data.get("tools", []) or []),
            "total_executions": data.get("total_executions", 0),
        }
    if report_type == "generation_analytics":
        return {
            "window_days": data.get("window_days"),
            **(data.get("summary") or {}),
        }
    if report_type == "comprehensive":
        return {
            "platform": data.get("platform", {}),
        }
    return {}


def _fail_dead(created_before, message: str) -> int:
    """Fail in-flight reports created before *created_before* that no live thread is generating."""
    candidates = list(
        Report.objects.filter(status__in=_IN_FLIGHT, created_at__lt=created_before).values_list("id", flat=True),
    )
    if not candidates:
        return 0
    live = _live_keys({_lock_key(rid) for rid in candidates})
    dead = [rid for rid in candidates if _lock_key(rid) not in live]
    if not dead:
        return 0
    return Report.objects.filter(id__in=dead, status__in=_IN_FLIGHT).update(
        status=Report.Status.FAILED,
        error_message=message,
        completed_at=timezone.now(),
    )


def reap_dead_reports(grace_seconds: int = DEAD_GRACE_SECONDS) -> int:
    """Fail pending/generating reports whose generating thread is gone (see module docstring)."""
    return _fail_dead(timezone.now() - timedelta(seconds=grace_seconds), _DEAD_MESSAGE)


def maybe_reap_dead_reports() -> int:
    """:func:`reap_dead_reports`, at most once per ``REAP_INTERVAL_SECONDS`` in this process."""
    global _last_reap  # noqa: PLW0603
    now = time.monotonic()
    if _last_reap and now - _last_reap < REAP_INTERVAL_SECONDS:
        return 0
    _last_reap = now
    try:
        return reap_dead_reports()
    except Exception:
        # Reaping is housekeeping: listing and opening reports must still work.
        logger.exception("Reaping dead reports failed")
        return 0


def fail_stuck_reports(older_than_minutes: int = 60) -> int:
    """Fail reports stuck in pending/generating for *older_than_minutes* (maintenance action).

    A report a live thread is still generating is never failed, however
    long it has been running.
    """
    threshold = timezone.now() - timedelta(minutes=older_than_minutes)
    return _fail_dead(threshold, f"Marked failed by maintenance: not finished after {older_than_minutes}m")


def list_reports(
    *,
    user=None,
    report_type: str | None = None,
    status: str | None = None,
    limit: int = 50,
    offset: int = 0,
    q: str = "",
    ordering: str = DEFAULT_LIST_ORDERING,
):
    """The user's reports, optionally filtered by type/status and a title search (*q*).

    *ordering* is a key of :data:`LIST_ORDERINGS` (ValueError otherwise).
    """
    if ordering not in LIST_ORDERINGS:
        msg = f"ordering must be one of: {', '.join(LIST_ORDERINGS)}"
        raise ValueError(msg)
    # Reports whose generating process died are failed here (throttled), so
    # the list never shows them "generating" forever.
    maybe_reap_dead_reports()
    qs = Report.objects.all()
    if user and user.is_authenticated:
        qs = qs.filter(created_by=user)
    if report_type:
        qs = qs.filter(report_type=report_type)
    if status:
        qs = qs.filter(status=status)
    q = (q or "").strip()
    if q:
        qs = qs.filter(title__icontains=q)
    total = qs.count()
    return qs.order_by(*LIST_ORDERINGS[ordering])[offset : offset + limit], total
