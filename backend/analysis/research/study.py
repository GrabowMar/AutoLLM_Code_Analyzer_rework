def _compute_preflight(study) -> tuple[dict[str, Any], dict[str, Any] | None]:
    """(preflight result, frozen plan or None). Never mutates."""
    stored_problems: list[dict[str, Any]] = []
    # Stored settings were valid when saved; an engine change (e.g. a removed
    # outcome) can invalidate them later, which must block, not crash.
    try:
        rules = validate_exclusion_rules(study.exclusion_rules)
    except ConfigError as exc:
        rules = validate_exclusion_rules({})
        stored_problems.append(_stored_problem("invalid_exclusion_rules", exc))
    try:
        design = validate_design(study.analysis_design)
    except ConfigError as exc:
        design = validate_design({})
        stored_problems.append(_stored_problem("invalid_design", exc))
    try:
        # The protocol freezes these questions; named confirmatory outcomes must be analysed.
        validate_research_questions(study.research_questions, design=design)
    except ConfigError as exc:
        stored_problems.append(_stored_problem("invalid_research_questions", exc))
    plan: dict[str, Any] | None = None
    plan_error: dict[str, Any] | None = None
    if study.profile_id is None:
        plan_error = {"code": "no_profile", "detail": "Pick an analysis profile for the study."}
    else:
        try:
            plan = plan_mod.freeze_plan(profile=study.profile, user=study.created_by)
        except ConfigError as exc:
            plan_error = {
                "code": "invalid_profile",
                "detail": f"The profile cannot be frozen into a plan: {exc}",
                "field_errors": exc.field_errors,
            }
        except sandbox.SandboxError as exc:
            plan_error = {"code": "plan_unavailable", "detail": f"The analyzer image is unavailable: {exc}"}
    try:
        jobs, notes = resolve_targets_detailed(study.target_spec, study.created_by)
    except ConfigError as exc:
        jobs = []
        notes = [
            {
                "code": "invalid_target_spec",
                "severity": "blocking",
                "detail": f"The target spec cannot be resolved: {exc}",
                "field_errors": exc.field_errors,
            },
        ]
    result = preflight_mod.preflight(
        user=study.created_by,
        plan=plan,
        jobs=jobs,
        exclusion_rules=rules,
        analysis_design=design,
        plan_error=plan_error,
        notes=[*stored_problems, *notes],
    )
    return json_safe(result), plan


def _stored_problem(code: str, exc: ConfigError) -> dict[str, Any]:
    return {"code": code, "severity": "blocking", "detail": str(exc), "field_errors": exc.field_errors}


def _require(study, action: str) -> None:
    allowed = TRANSITIONS[action]
    if study.status not in allowed:
        msg = (
            f"Cannot {action.replace('_', ' ')} a study in status '{study.status}' "
            f"(allowed from: {', '.join(allowed)})."
        )
        raise StudyError(msg, code="invalid_state")


def allowed_actions(study) -> dict[str, bool]:
    """UI hints: which lifecycle actions the study's status allows (launch also resumes a pending launch)."""
    actions = {action: study.status in statuses for action, statuses in TRANSITIONS.items()}
    actions["launch"] = actions["launch"] or launch_pending(study)
    return actions


def require(study, action: str) -> None:
    """Raise :class:`StudyError` unless *action* is allowed in the study's status."""
    _require(study, action)


def _locked_row(study):
    # of=("self",): only the study row; Postgres cannot lock the nullable side of the profile join.
    return (
        AnalysisStudy.objects.select_for_update(of=("self",)).select_related("profile", "created_by").get(pk=study.pk)
    )


def run_preflight(study) -> dict[str, Any]:
    """Compute the pre-run checks and store them on ``study.preflight`` (draft only)."""
    with transaction.atomic():
        study = _locked_row(study)
        _require(study, "preflight")
        result, _plan = _compute_preflight(study)
        study.preflight = result
        study.save(update_fields=["preflight", "updated_at"])
    return result


def lock(study, *, user):
    """Freeze plan + protocol (sha256); refuses when preflight has blocking issues.

    The fresh preflight is stored even when the lock is refused, so the
    researcher sees exactly why.
    """
    refused: dict[str, Any] | None = None
    with transaction.atomic():
        study = _locked_row(study)
        _require(study, "lock")
        if study.profile_id is None:
            msg = "Pick an analysis profile before locking the protocol."
            raise StudyError(msg, code="no_profile")
        result, plan = _compute_preflight(study)
        study.preflight = result
        if result.get("blocking") or plan is None:
            study.save(update_fields=["preflight", "updated_at"])
            refused = result
        else:
            study.plan = json_safe(plan)
            study.plan_hash = result.get("plan_hash") or plan_mod.plan_hash(plan)
            study.status = Status.LOCKED
            study.locked_at = timezone.now()
            # build_protocol reads the instance (plan, preflight, design, ...).
            protocol = json_safe(report_mod.build_protocol(study))
            study.protocol = protocol
            study.protocol_hash = protocol_hash(protocol)
            study.save(
                update_fields=[
                    "preflight",
                    "plan",
                    "plan_hash",
                    "status",
                    "locked_at",
                    "protocol",
                    "protocol_hash",
                    "updated_at",
                ],
            )
    if refused is not None:
        msg = "The preflight has blocking issues; resolve them before locking the protocol."
        raise StudyError(msg, code="blocking_issues", extra={"blocking": refused.get("blocking", [])})
    logger.info("Study %s locked by user %s (protocol %s)", study.pk, getattr(user, "pk", None), study.protocol_hash)
    return study


def unlock(study, *, user):
    """Back to draft (only before launch): the frozen plan and protocol are discarded."""
    with transaction.atomic():
        study = _locked_row(study)
        _require(study, "unlock")
        study.status = Status.DRAFT
        study.plan = {}
        study.plan_hash = ""
        study.protocol = {}
        study.protocol_hash = ""
        study.locked_at = None
        study.save(
            update_fields=["status", "plan", "plan_hash", "protocol", "protocol_hash", "locked_at", "updated_at"],
        )
    logger.info("Study %s unlocked by user %s", study.pk, getattr(user, "pk", None))
    return study


