"""Study lifecycle: draft -> preflight -> locked protocol -> running -> completed (owner: API/research stage).

target_spec::

    {"kind": "experiment" | "batch" | "jobs" | "filter",
     "experiment_id": uuid, "condition_ids": [int], "app_slugs": [str],
     "batch_id": uuid, "job_ids": [uuid],
     "filters": {"model_ids": [...], "modes": [...], "harnesses": [...], "stacks": [...],
                 "app_slugs": [...], "created_after": iso, "created_before": iso, "status": "completed"}}

Only the requesting user's (or, for staff, any) completed jobs are targets.
Explicit references (an experiment, a batch, job ids) may point at another
user's data only for staff; a ``filter`` spec always selects the user's own
jobs, so a staff researcher's study never silently pools everyone's apps.

State machine (strict; every transition locks the study row)::

    draft --lock--> locked --launch--> running --(every run terminal)--> completed
      ^               |                  |  ^                                |
      +----unlock-----+                  |  +----------retry-failed----------+
    cancel: from draft, locked or running -> cancelled

``lock`` re-runs the preflight with a freshly frozen plan, refuses on any
blocking issue, then freezes ``plan`` + ``plan_hash`` and the protocol
(``report.build_protocol``) + ``protocol_hash``. ``launch`` verifies both
hashes and the analyzer image synchronously, marks the study running and
hands the submission to a background job (:func:`submit_launch`), which
submits one run per *eligible protocol target*; targets that cannot be
submitted (job gone, code changed since the lock) are recorded in
``preflight["launch"]``, never silently dropped. The job is idempotent (a
target that already has a run in the study is skipped), so calling
``launch`` again resumes a launch that was interrupted. While a launch is
submitting the study never completes.

``preflight["launch"]``::

    {"status": "submitting" | "interrupted" | "submitted" | "failed" | "cancelled",
     "planned", "submitted", "run_ids": [...], "skipped": [{job_id, label, reason, detail?}],
     "launched_at", "launched_by", "requested_at", "finished_at", "attempts", "error"}

Post-run report (``study.report``), generated by a background job
(:func:`request_report` -> :func:`generate_report`)::

    {}                                                    never requested
    {"status": "generating", "request_id", "requested_at", "requested_by"}
    {"status": "failed", "request_id", "requested_at", "failed_at", "error"}
    {...report.build_report(...), "status": "ready"}      (``status`` is not hashed)

The executor calls :func:`on_run_finished` when a study run becomes
terminal; reads also call :func:`refresh`, so a study completes even when a
hook was missed.
"""

