def report_state(study, *, report: dict[str, Any] | None = None) -> dict[str, Any] | None:
    """Lifecycle of ``study.report``: None when never requested, else
    ``{status: generating|failed|ready, request_id, requested_at, generated_at, error, report_hash}``.

    A ``generating`` marker older than :data:`REPORT_STALE_SECONDS` lost its
    worker and is reported as failed, so a client polling it terminates.
    *report* replaces ``study.report`` when only its top-level lifecycle
    keys were loaded (``status``, ``kind``, ``request_id``, ``requested_at``, ``error``).
    """
    if report is None:
        report = study.report if isinstance(study.report, dict) else {}
    if not report:
        return None
    status = report.get("status")
    error = report.get("error") or None
    if status not in ("generating", "failed"):
        if report_mod.is_report(report):
            status = "ready"
        else:
            status, error = "failed", "The stored report is not a recognised report document."
    elif status == "generating" and _report_request_stale(report):
        status = "failed"
        error = "The report job did not finish (its worker was lost or timed out); request the report again."
    ready = status == "ready"
    return {
        "status": status,
        "request_id": report.get("request_id"),
        "requested_at": report.get("requested_at"),
        "generated_at": study.report_generated_at.isoformat() if ready and study.report_generated_at else None,
        "error": None if ready else error,
        "report_hash": (study.report_hash or None) if ready else None,
    }


def _report_request_stale(report: dict[str, Any]) -> bool:
    requested = parse_datetime(str(report.get("requested_at") or ""))
    return requested is None or timezone.now() - requested > timedelta(seconds=REPORT_STALE_SECONDS)


def ready_report(study) -> dict[str, Any] | None:
    """The stored report when one is ready (never rebuilt here), else None."""
    state = report_state(study)
    return study.report if state is not None and state["status"] == "ready" else None


def report_is_stale(study) -> bool | None:
    """Whether the stored report no longer reflects the study's data (None without a ready report).

    Stale when a study run changed after the report was generated, or when
    the canonical analysis set differs from the report's
    ``inputs.analysis_run_ids``: deleting a run (or the job behind a target)
    changes the selection without updating any remaining run.
    """
    report = ready_report(study)
    if report is None or study.report_generated_at is None:
        return None
    if study.runs.filter(updated_at__gt=study.report_generated_at).exists():
        return True
    stored = (report.get("inputs") or {}).get("analysis_run_ids") if isinstance(report, dict) else None
    if not isinstance(stored, list):
        return False
    return sorted(str(i) for i in stored) != report_mod.current_analysis_run_ids(study)


def verify_report_inputs(study) -> None:
    """Refuse (StudyError) when the stored protocol or plan no longer matches its sha256.

    The report links to the protocol and the plan by hash and presents its
    analysis as the pre-registered one: a report built from a protocol that
    fails its own hash would cite a pre-registration nobody can verify. A
    study cancelled before lock has neither and passes.
    """
    if (study.protocol or study.protocol_hash) and not verify_protocol(study):
        msg = "Protocol integrity check failed: the stored protocol does not match its hash."
        raise StudyError(msg, code="protocol_integrity")
    if study.plan_hash and (not study.plan or plan_mod.plan_hash(study.plan) != study.plan_hash):
        msg = "Plan integrity check failed: the frozen plan does not match its hash."
        raise StudyError(msg, code="plan_integrity")


def request_report(study, *, user) -> dict[str, Any]:
    """Mark the report as generating and dispatch :func:`generate_report` after commit; returns the state.

    Idempotent while a request is in flight (the pending request's state is
    returned and nothing is dispatched). A new request replaces the stored
    report: it was built from the data at its own generation time. Refused
    (409 ``protocol_integrity`` / ``plan_integrity``) when the frozen
    protocol or plan fails its hash (:func:`verify_report_inputs`).
    """
    with transaction.atomic():
        study = refresh(_locked_row(study))
        _require(study, "report")
        verify_report_inputs(study)
        if not study.runs.exclude(purpose=AnalysisRun.Purpose.CANARY).exists():
            msg = "The study has no runs to report on."
            raise StudyError(msg, code="no_runs")
        state = report_state(study)
        if state is not None and state["status"] == "generating":
            return state
        request_id = uuid.uuid4().hex
        study.report = {
            "status": "generating",
            "request_id": request_id,
            "requested_at": timezone.now().isoformat(),
            "requested_by": getattr(user, "pk", None),
        }
        study.report_hash = ""
        study.report_generated_at = None
        study.save(update_fields=["report", "report_hash", "report_generated_at", "updated_at"])
        transaction.on_commit(partial(_dispatch_report, str(study.pk), request_id))
    return report_state(study) or {}


def _dispatch_report(study_id: str, request_id: str) -> None:
    from backend.analysis import tasks

    tasks.dispatch_study_report(study_id, request_id)


def _current_request(study, request_id: str) -> bool:
    report = study.report if isinstance(study.report, dict) else {}
    return report.get("status") == "generating" and report.get("request_id") == request_id


def generate_report(study_id, request_id: str) -> str:
    """Background half of :func:`request_report`: build the report from stored data and store it.

    Only the request that is still current writes (a superseded or
    redelivered job is a no-op). Never raises: a failure is stored as
    ``{"status": "failed", "error"}``. Returns the outcome: ``ready``,
    ``failed``, ``superseded`` or ``missing``.
    """
    try:
        study = AnalysisStudy.objects.select_related("profile", "created_by").filter(pk=study_id).first()
        if study is None:
            return "missing"
        if not _current_request(study, request_id):
            return "superseded"
        # Checked again here: the job may run well after the request was accepted.
        verify_report_inputs(study)
        # The data snapshot starts here: a run changed after this instant makes the report stale.
        started = timezone.now()
        report = json_safe(report_mod.build_report(study))
        report["status"] = "ready"
        with transaction.atomic():
            locked = AnalysisStudy.objects.select_for_update().filter(pk=study_id).first()
            if locked is None or not _current_request(locked, request_id):
                return "superseded"
            locked.report = report
            locked.report_hash = report_mod.report_hash(report)
            locked.report_generated_at = started
            locked.save(update_fields=["report", "report_hash", "report_generated_at", "updated_at"])
    except Exception as exc:
        logger.exception("Generating the report of study %s failed", study_id)
        return _store_report_failure(study_id, request_id, exc)
    logger.info("Study %s report generated (%s)", study_id, locked.report_hash[:12])
    return "ready"


def _store_report_failure(study_id, request_id: str, exc: BaseException) -> str:
    try:
        with transaction.atomic():
            locked = AnalysisStudy.objects.select_for_update().filter(pk=study_id).first()
            if locked is None or not _current_request(locked, request_id):
                return "superseded"
            locked.report = {
                "status": "failed",
                "request_id": request_id,
                "requested_at": locked.report.get("requested_at"),
                "failed_at": timezone.now().isoformat(),
                "error": f"{type(exc).__name__}: {exc}"[:MAX_ERROR_CHARS],
            }
            locked.save(update_fields=["report", "updated_at"])
    except Exception:
        logger.exception("Could not record the failed report of study %s", study_id)
    return "failed"
