def json_safe(value: Any) -> Any:
    """Recursively make *value* storable in a JSONField and hashable canonically.

    Non-finite floats become None (Postgres jsonb rejects NaN; missing data is
    None, never 0), tuples/sets become lists, UUIDs/datetimes become strings.
    """
    if isinstance(value, float):
        out: Any = value if math.isfinite(value) else None
    elif value is None or isinstance(value, (bool, int, str)):
        out = value
    elif isinstance(value, dict):
        out = {str(k): json_safe(v) for k, v in value.items()}
    elif isinstance(value, (list, tuple)):
        out = [json_safe(v) for v in value]
    elif isinstance(value, (set, frozenset)):
        out = sorted((json_safe(v) for v in value), key=lambda v: json.dumps(v, sort_keys=True, default=str))
    elif isinstance(value, datetime):
        out = value.isoformat()
    else:
        out = str(value)
    return out


