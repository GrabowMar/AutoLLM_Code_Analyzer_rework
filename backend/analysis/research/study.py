def _is_staff(user) -> bool:
    return bool(getattr(user, "is_staff", False))


def job_queryset():
    """GenerationJobs with everything ``sample.target_meta`` reads, plus ``harness_name``."""
    from backend.generation.models import GenerationJob
    from backend.generation.services.job_listing import harness_expression

    return GenerationJob.objects.select_related(
        "model",
        "condition",
        "experiment",
        "batch",
        "app_requirement",
    ).annotate(harness_name=harness_expression())


def _apply_filters(qs, filters: dict[str, Any]):
    if model_ids := filters.get("model_ids"):
        ints = [v for v in model_ids if isinstance(v, int)]
        strs = [v for v in model_ids if isinstance(v, str)]
        qs = qs.filter(Q(model_id__in=ints) | Q(model__model_id__in=strs) | Q(model__canonical_slug__in=strs))
    if modes := filters.get("modes"):
        qs = qs.filter(mode__in=modes)
    if harnesses := filters.get("harnesses"):
        qs = qs.filter(Q(harness_name__in=harnesses) | Q(condition__harness__in=harnesses))
    if stacks := filters.get("stacks"):
        qs = qs.filter(stack_slug__in=stacks)
    if app_slugs := filters.get("app_slugs"):
        qs = qs.filter(app_requirement__slug__in=app_slugs)
    if after := filters.get("created_after"):
        qs = qs.filter(created_at__gte=parse_datetime(after))
    if before := filters.get("created_before"):
        qs = qs.filter(created_at__lt=parse_datetime(before))
    return qs


def _scope_owner(qs, user, *, explicit: bool):
    """Restrict to the user's jobs unless a staff user referenced the data explicitly."""
    if explicit and _is_staff(user):
        return qs
    return qs.filter(created_by=user)


def resolve_targets_detailed(target_spec: dict[str, Any], user) -> tuple[list, list[dict[str, Any]]]:
    """``(jobs, notes)``: the completed target jobs in a deterministic order, plus
    notes about requested jobs that are not targets (not found, not completed)."""
    from backend.generation.models import Experiment
    from backend.generation.models import GenerationBatch
    from backend.generation.models import GenerationJob

    spec = validate_target_spec(target_spec)
    kind = spec["kind"]
    notes: list[dict[str, Any]] = []
    qs = job_queryset()
    order: tuple[str, ...] = ("created_at", "id")
    if kind == "experiment":
        experiments = Experiment.objects.filter(id=spec["experiment_id"])
        if not _is_staff(user):
            experiments = experiments.filter(created_by=user)
        if (experiment := experiments.first()) is None:
            raise ConfigError({"target_spec.experiment_id": "experiment not found"})
        qs = qs.filter(experiment=experiment)
        if condition_ids := spec.get("condition_ids"):
            qs = qs.filter(condition_id__in=condition_ids)
        if app_slugs := spec.get("app_slugs"):
            qs = qs.filter(app_requirement__slug__in=app_slugs)
        qs = _scope_owner(qs, user, explicit=True)
        order = ("condition_id", "app_requirement__slug", "repeat_index", "created_at", "id")
    elif kind == "batch":
        batches = GenerationBatch.objects.filter(id=spec["batch_id"])
        if not _is_staff(user):
            batches = batches.filter(created_by=user)
        if (batch := batches.first()) is None:
            raise ConfigError({"target_spec.batch_id": "batch not found"})
        qs = _scope_owner(qs.filter(batch=batch), user, explicit=True)
    elif kind == "jobs":
        qs = _scope_owner(qs.filter(id__in=spec["job_ids"]), user, explicit=True)
    else:
        qs = _scope_owner(qs, user, explicit=False)
    qs = _apply_filters(qs, spec.get("filters") or {})
    completed = GenerationJob.Status.COMPLETED
    jobs = list(qs.filter(status=completed).order_by(*order))
    if kind == "jobs":
        found = {str(j.id) for j in jobs}
        if missing := [jid for jid in spec["job_ids"] if jid not in found]:
            notes.append(
                {
                    "code": "jobs_unavailable",
                    "detail": f"{len(missing)} requested job(s) are not targets "
                    "(not found, not yours, or not completed)",
                    "job_ids": missing[:200],
                },
            )
    elif not_completed := qs.exclude(status=completed).count():
        notes.append(
            {
                "code": "jobs_not_completed",
                "detail": f"{not_completed} matching job(s) are not completed and are not targets",
            },
        )
    return jobs, notes


def resolve_targets(target_spec: dict[str, Any], user) -> list:
    jobs, _notes = resolve_targets_detailed(target_spec, user)
    return jobs


