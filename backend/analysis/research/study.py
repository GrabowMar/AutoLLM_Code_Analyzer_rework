def _number_in(value: Any, lo: float, hi: float) -> bool:
    return not isinstance(value, bool) and isinstance(value, (int, float)) and lo < value < hi


def _int_in(value: Any, lo: int, hi: int) -> bool:
    return not isinstance(value, bool) and isinstance(value, int) and lo <= value <= hi


def validate_design(design: Any) -> dict[str, Any]:
    """Defaults merged with *design*; raises ConfigError with ``analysis_design.*`` paths.

    ``group_by`` is a factor or a list of factors (crossed), ``block_by`` a
    factor that is not also a grouping factor (or null).
    """
    out = copy.deepcopy(DEFAULT_DESIGN)
    if design in (None, {}):
        return out
    if not isinstance(design, dict):
        raise ConfigError({"analysis_design": "must be an object"})
    errors: dict[str, str] = {}
    base = "analysis_design"
    for key in design:
        if key not in DEFAULT_DESIGN:
            errors[f"{base}.{key}"] = "unknown field"
    if "group_by" in design:
        group_by = design["group_by"]
        group_by = [group_by] if isinstance(group_by, str) else group_by
        if not isinstance(group_by, list) or not group_by or any(g not in GROUP_BY for g in group_by):
            errors[f"{base}.group_by"] = f"must be one or more of {', '.join(GROUP_BY)}"
        else:
            out["group_by"] = list(dict.fromkeys(group_by))
    if "block_by" in design:
        block_by = design["block_by"] or None
        if block_by is not None and block_by not in GROUP_BY:
            errors[f"{base}.block_by"] = f"must be null or one of {', '.join(GROUP_BY)}"
        else:
            out["block_by"] = block_by
    if out["block_by"] in out["group_by"]:
        if "block_by" in design:
            errors[f"{base}.block_by"] = "cannot also be a grouping factor"
        else:
            out["block_by"] = None
    checks = (
        ("alpha", lambda v: _number_in(v, 0.0, 0.5), "must be a number in (0, 0.5)"),
        ("ci_level", lambda v: _number_in(v, 0.5, 0.9999), "must be a number in (0.5, 0.9999)"),
        ("bootstrap_resamples", lambda v: _int_in(v, 0, MAX_RESAMPLES), f"must be an integer 0..{MAX_RESAMPLES}"),
        ("effect_ci_resamples", lambda v: _int_in(v, 0, MAX_RESAMPLES), f"must be an integer 0..{MAX_RESAMPLES}"),
        ("seed", lambda v: _int_in(v, 0, 2**63 - 1), "must be a non-negative integer"),
        ("correction", lambda v: v in CORRECTIONS, f"must be one of {', '.join(CORRECTIONS)}"),
        ("exploratory_correction", lambda v: v in CORRECTIONS, f"must be one of {', '.join(CORRECTIONS)}"),
        ("cell_aggregate", lambda v: v in CELL_AGGREGATES, f"must be one of {', '.join(CELL_AGGREGATES)}"),
    )
    for key, ok, message in checks:
        if key in design:
            if ok(design[key]):
                out[key] = design[key]
            else:
                errors[f"{base}.{key}"] = message
    known = _outcome_keys()
    if "primary_outcome" in design:
        if design["primary_outcome"] not in known:
            errors[f"{base}.primary_outcome"] = "unknown outcome"
        else:
            out["primary_outcome"] = design["primary_outcome"]
    if "outcomes" in design and design["outcomes"] is not None:
        outcomes = design["outcomes"]
        if not isinstance(outcomes, list) or not outcomes or not all(isinstance(k, str) for k in outcomes):
            errors[f"{base}.outcomes"] = "must be null (every outcome) or a non-empty list of outcome keys"
        elif unknown := [k for k in outcomes if k not in known]:
            errors[f"{base}.outcomes"] = f"unknown outcome(s): {', '.join(unknown)}"
        else:
            out["outcomes"] = list(dict.fromkeys(outcomes))
    if errors:
        raise ConfigError(errors)
    return out


RQ_FIELDS = ("id", "text", "kind", "hypothesis", "outcome", "outcomes")


def _rq_outcomes(raw: dict[str, Any], kind: str, path: str, errors: dict[str, str]) -> list[str] | None:
    """The outcome keys a question names (``outcome`` and/or ``outcomes``), validated; None when none."""
    named: list[Any] = []
    if raw.get("outcome") not in (None, ""):
        if not isinstance(raw["outcome"], str):
            errors[f"{path}.outcome"] = "must be an outcome key"
            return None
        named.append(raw["outcome"])
    if raw.get("outcomes") not in (None, []):
        if not isinstance(raw["outcomes"], list) or not all(isinstance(k, str) and k for k in raw["outcomes"]):
            errors[f"{path}.outcomes"] = "must be a list of outcome keys"
            return None
        named.extend(raw["outcomes"])
    if not named:
        return None
    field = "outcomes" if raw.get("outcomes") not in (None, []) else "outcome"
    if kind != "confirmatory":
        errors[f"{path}.{field}"] = (
            "only confirmatory questions name outcomes (they join the confirmatory family); "
            "exploratory questions cover every outcome"
        )
        return None
    if unknown := [k for k in named if k not in _outcome_keys()]:
        errors[f"{path}.{field}"] = f"unknown outcome(s): {', '.join(unknown)}"
        return None
    return list(dict.fromkeys(named))


def validate_research_questions(questions: Any, *, design: dict[str, Any] | None = None) -> list[dict[str, Any]]:
    """``[{id, text, kind, hypothesis?, outcomes?}]`` with ids defaulting to RQ1..n (unique).

    A confirmatory question may name the outcomes it tests (``outcome``: a
    key, or ``outcomes``: a list; stored as ``outcomes``); they join the
    primary outcome in the confirmatory (strictly corrected) family of the
    report. With *design* (validated), a named outcome must be one the
    design analyses (its ``outcomes`` subset, or the primary outcome).
    """
    if questions in (None, []):
        return []
    if not isinstance(questions, list):
        raise ConfigError({"research_questions": "must be a list"})
    if len(questions) > MAX_RESEARCH_QUESTIONS:
        raise ConfigError({"research_questions": f"at most {MAX_RESEARCH_QUESTIONS} questions"})
    errors: dict[str, str] = {}
    out: list[dict[str, Any]] = []
    seen: set[str] = set()
    for i, raw in enumerate(questions):
        path = f"research_questions.{i}"
        if not isinstance(raw, dict):
            errors[path] = "must be an object"
            continue
        if unknown := [k for k in raw if k not in RQ_FIELDS]:
            errors[f"{path}.{unknown[0]}"] = "unknown field"
        text = raw.get("text")
        if not isinstance(text, str) or not text.strip():
            errors[f"{path}.text"] = "required"
            continue
        kind = raw.get("kind") or "exploratory"
        if kind not in RQ_KINDS:
            errors[f"{path}.kind"] = f"must be one of {', '.join(RQ_KINDS)}"
            continue
        qid = str(raw.get("id") or f"RQ{i + 1}").strip()[:20]
        if qid in seen:
            errors[f"{path}.id"] = "duplicate id"
            continue
        seen.add(qid)
        item = {"id": qid, "text": text.strip()[:2000], "kind": kind}
        if isinstance(raw.get("hypothesis"), str) and raw["hypothesis"].strip():
            item["hypothesis"] = raw["hypothesis"].strip()[:2000]
        if (outcomes := _rq_outcomes(raw, kind, path, errors)) is not None:
            item["outcomes"] = outcomes
        out.append(item)
    if design is not None and not errors:
        errors.update(question_outcome_errors(out, design))
    if errors:
        raise ConfigError(errors)
    return out


def question_outcome_errors(questions: list[dict[str, Any]], design: dict[str, Any]) -> dict[str, str]:
    """Field errors for confirmatory questions naming outcomes the (validated) *design* does not analyse.

    The report analyses ``design["outcomes"]`` (every outcome when null)
    plus the primary outcome; a named outcome outside that set would be
    silently missing from the confirmatory family.
    """
    analysed = design.get("outcomes")
    if not analysed:
        return {}
    allowed = {*analysed, design.get("primary_outcome")}
    errors: dict[str, str] = {}
    for i, rq in enumerate(questions if isinstance(questions, list) else []):
        named = rq.get("outcomes") if isinstance(rq, dict) else None
        if missing := [k for k in named if k not in allowed] if isinstance(named, list) else []:
            errors[f"research_questions.{i}.outcomes"] = (
                f"not analysed by the design: {', '.join(missing)} (add to analysis_design.outcomes)"
            )
    return errors


