def verify_protocol(study) -> bool:
    """True when the stored protocol still matches its sha256."""
    return bool(study.protocol) and protocol_hash(study.protocol) == study.protocol_hash


def _verify_frozen(study) -> None:
    if not study.protocol or not study.protocol_hash:
        msg = "The study has no frozen protocol."
        raise StudyError(msg, code="no_protocol")
    if not verify_protocol(study):
        msg = "Protocol integrity check failed: the stored protocol does not match its hash."
        raise StudyError(msg, code="protocol_integrity")
    if not study.plan or plan_mod.plan_hash(study.plan) != study.plan_hash:
        msg = "Plan integrity check failed: the frozen plan does not match its hash."
        raise StudyError(msg, code="plan_integrity")
    planned_tag = ((study.plan or {}).get("analyzer_image") or {}).get("tag") or ""
    if planned_tag:
        current = sandbox.image_tag()
        if current != planned_tag:
            msg = (
                f"The analyzer image changed since the protocol was locked ({planned_tag} -> {current}); "
                "unlock and lock the study again."
            )
            raise StudyError(msg, code="image_changed", extra={"planned_tag": planned_tag, "current_tag": current})
    check_procedure(study.plan)


def check_procedure(plan: dict[str, Any] | None, *, tools: list[str] | None = None) -> None:
    """Refuse (409 ``procedure_drift``) when the running code no longer implements *plan*'s frozen procedure.

    The executor would fail such runs one by one (a drifted tool fails with
    ``procedure_drift``, a changed engine stage or mapping table fails the
    whole run), so launching or retrying them only spends time and AI
    budget on results that cannot carry the study's ``plan_hash``. *tools*
    limits the tool check to the tools being (re)run; engine and mapping
    drift always refuse.
    """
    plan = plan if isinstance(plan, dict) else {}
    if not plan:
        return
    drift = plan_mod.procedure_drift(plan)
    tool_drift = {
        slug: reason for slug, reason in (drift.get("tools") or {}).items() if tools is None or slug in tools
    }
    engine = list(drift.get("engine") or [])
    mappings = normalize.mapping_drift(plan.get("mapping_hashes"))
    if not (tool_drift or engine or mappings):
        return
    parts = [*engine, *tool_drift.values()]
    parts += [f"mapping table {name} changed" for name in mappings if not any(name in e for e in engine)]
    msg = (
        "The running code no longer implements the procedure frozen in the study's plan ("
        + "; ".join(parts)
        + "). Unlock and lock the study again to freeze a new plan."
    )
    raise StudyError(
        msg,
        code="procedure_drift",
        extra={"tools": tool_drift, "engine": engine, "mappings": mappings},
    )


def launch_state(study) -> dict[str, Any]:
    """``study.preflight["launch"]`` (``{}`` before launch)."""
    launch = (study.preflight or {}).get("launch") if isinstance(study.preflight, dict) else None
    return launch if isinstance(launch, dict) else {}


def launch_pending(study) -> bool:
    """True while a running study's runs are being submitted, or the submission can be resumed."""
    return study.status == Status.RUNNING and launch_state(study).get("status") in LAUNCH_PENDING


def _protocol_targets(study) -> list[dict[str, Any]]:
    """The locked protocol's eligible targets (hash-verified, unlike the preflight)."""
    resolved = ((study.protocol or {}).get("targets") or {}).get("resolved") or []
    return [t for t in resolved if isinstance(t, dict) and t.get("eligible") and t.get("job_id")]


def launch(study, *, user):
    """Verify the frozen protocol, mark the study running and submit its runs in the background.

    Runs belong to the study owner (their API key pays for AI reviews). The
    submission (:func:`submit_launch`) is dispatched after commit; calling
    ``launch`` on a running study whose launch is pending resumes it.
    Refused (nothing changes) when the protocol, the plan or the analyzer
    image no longer match, or when the protocol has no eligible target.
    """
    with transaction.atomic():
        study = _locked_row(study)
        resuming = launch_pending(study)
        if not resuming:
            _require(study, "launch")
        _verify_frozen(study)
        targets = _protocol_targets(study)
        if not targets:
            msg = "The protocol has no eligible target to launch."
            raise StudyError(msg, code="nothing_to_launch", extra={"skipped": []})
        now = timezone.now()
        previous = launch_state(study) if resuming else {}
        state = {
            "status": "submitting",
            "planned": len(targets),
            "eligible_targets": len(targets),
            "submitted": study.runs.exclude(purpose=AnalysisRun.Purpose.CANARY).count() if resuming else 0,
            "run_ids": list(previous.get("run_ids") or []),
            "skipped": list(previous.get("skipped") or []),
            "launched_at": previous.get("launched_at") or now,
            "launched_by": previous.get("launched_by") or getattr(user, "pk", None),
            "requested_at": now,
            "finished_at": None,
            "attempts": int(previous.get("attempts") or 0) + 1,
            "error": "",
        }
        if not resuming:
            study.status = Status.RUNNING
            study.launched_at = now
        study.preflight = {**(study.preflight or {}), "launch": json_safe(state)}
        study.save(update_fields=["status", "launched_at", "preflight", "updated_at"])
        transaction.on_commit(partial(_dispatch_launch, str(study.pk)))
    logger.info("Study %s launch %s: %d planned targets", study.pk, "resumed" if resuming else "started", len(targets))
    return study


def _dispatch_launch(study_id: str) -> None:
    from backend.analysis import tasks

    tasks.dispatch_study_launch(study_id)


def submit_launch(study_id) -> dict[str, Any] | None:
    """Background half of :func:`launch`: one run per eligible protocol target without a run yet.

    Idempotent: a target that already has a run in this study is skipped,
    and every submission re-checks that under the study row lock, so a
    resumed or duplicated launch never doubles a target. Stops when the
    study is cancelled. Never raises: an unexpected error marks the launch
    ``interrupted`` (resumable). Returns the final launch state, or None
    when there was nothing to do.
    """
    try:
        return _submit_launch(study_id)
    except Exception as exc:
        logger.exception("Launching study %s was interrupted", study_id)
        try:
            return _finish_launch(study_id, skipped=None, error=f"{type(exc).__name__}: {exc}")
        except Exception:
            logger.exception("Could not record the interrupted launch of study %s", study_id)
            return None


def _submit_launch(study_id) -> dict[str, Any] | None:
    from backend.generation.models import GenerationJob

    study = AnalysisStudy.objects.select_related("profile", "created_by").filter(pk=study_id).first()
    if study is None or not launch_pending(study):
        return None
    owner = study.created_by
    targets = _protocol_targets(study)
    job_qs = _scope_owner(job_queryset().filter(id__in=[t["job_id"] for t in targets]), owner, explicit=True)
    jobs = {str(j.id): j for j in job_qs}
    scope = (study.plan or {}).get("scope")
    done = {str(pk) for pk in study.runs.exclude(generation_job_id=None).values_list("generation_job_id", flat=True)}
    skipped: list[dict[str, Any]] = []
    for target in targets:
        job_id = str(target["job_id"])
        if job_id in done:
            continue
        label = target.get("label") or job_id
        job = jobs.get(job_id)
        if job is None:
            skipped.append({"job_id": job_id, "label": label, "reason": "job_missing"})
            continue
        if job.status != GenerationJob.Status.COMPLETED:
            skipped.append({"job_id": job_id, "label": label, "reason": "job_not_completed"})
            continue
        # Resolving the sample is the slow part: done outside the row lock.
        try:
            smp = sample_mod.resolve_job(job, scope)
        except SampleUnavailable as exc:
            skipped.append({"job_id": job_id, "label": label, "reason": "sample_unavailable", "detail": str(exc)})
            continue
        expected_hash = target.get("sample_hash") or ""
        if expected_hash and smp.sample_hash != expected_hash:
            skipped.append(
                {
                    "job_id": job_id,
                    "label": label,
                    "reason": "sample_changed",
                    "detail": f"sample hash {smp.sample_hash[:12]} != protocol {expected_hash[:12]}",
                },
            )
            continue
        with transaction.atomic():
            locked = _locked_row(study)
            if not launch_pending(locked):
                # Cancelled, or another launcher already finished the job.
                break
            if locked.runs.filter(generation_job_id=job.id).exists():
                continue
            try:
                # Own savepoint: a refused submission leaves nothing half-written.
                with transaction.atomic():
                    executor.submit_run(
                        user=owner,
                        plan=locked.plan,
                        profile=locked.profile,
                        generation_job=job,
                        sample=smp,
                        study=locked,
                        purpose=AnalysisRun.Purpose.RESEARCH,
                        name=f"{locked.name}: {label}"[:200],
                    )
            except (ValueError, PermissionError) as exc:
                skipped.append({"job_id": job_id, "label": label, "reason": "submit_failed", "detail": str(exc)})
    return _finish_launch(study_id, skipped=skipped)


def _finish_launch(study_id, *, skipped: list[dict[str, Any]] | None, error: str = "") -> dict[str, Any] | None:
    """Record the outcome of a launch job (row-locked); a finished launch's record is never overwritten.

    A launch that submitted nothing at all returns the study to ``locked``
    (``status: failed``), as if it had never been launched. A launch the
    study's cancel stopped keeps ``cancelled`` but gets its final counts.
    """
    with transaction.atomic():
        study = AnalysisStudy.objects.select_for_update().filter(pk=study_id).first()
        if study is None:
            return None
        state = dict(launch_state(study))
        if state.get("status") not in (*LAUNCH_PENDING, "cancelled"):
            return state
        run_ids = [
            str(pk)
            for pk in study.runs.exclude(purpose=AnalysisRun.Purpose.CANARY)
            .order_by("created_at", "id")
            .values_list("id", flat=True)
        ]
        state.update(
            submitted=len(run_ids),
            run_ids=run_ids,
            finished_at=timezone.now(),
            error=error[:MAX_ERROR_CHARS],
        )
        if skipped is not None:
            state["skipped"] = skipped
        fields = ["preflight", "updated_at"]
        if study.status != Status.RUNNING:
            state["status"] = "cancelled"
        elif error:
            state["status"] = "interrupted"
        elif not run_ids:
            state.update(status="failed", error=NO_TARGET_SUBMITTED)
            study.status = Status.LOCKED
            study.launched_at = None
            fields += ["status", "launched_at"]
        else:
            state["status"] = "submitted"
        study.preflight = {**(study.preflight or {}), "launch": json_safe(state)}
        study.save(update_fields=fields)
        if state["status"] == "submitted":
            # Runs may all have finished while the launch was still submitting.
            refresh(study)
    logger.info(
        "Study %s launch %s: %d submitted, %d skipped",
        study_id,
        state["status"],
        state["submitted"],
        len(state.get("skipped") or []),
    )
    return state


