# Running: progress, cancel, retry, refresh
# --------------------------------------------------------------------------


def refresh(study):
    """Move a running study to completed once its launch is done and every run is terminal."""
    if study.status != Status.RUNNING or launch_pending(study):
        return study
    if study.runs.filter(status__in=AnalysisRun.ACTIVE_STATUSES).exists():
        return study
    now = timezone.now()
    updated = AnalysisStudy.objects.filter(pk=study.pk, status=Status.RUNNING).update(
        status=Status.COMPLETED,
        completed_at=now,
        updated_at=now,
    )
    if updated:
        study.status = Status.COMPLETED
        study.completed_at = now
    else:
        study.refresh_from_db()
    return study


def on_run_finished(run) -> None:
    """Executor hook: a run became terminal; complete its study when that was the last active run.

    Locks the study row, so two runs finishing at once (each possibly
    inside its own uncommitted transaction) are checked one after the
    other and the second one sees the first as terminal. Never raises: a
    failure here must not fail the run; reads call :func:`refresh` anyway.
    """
    study_id = getattr(run, "study_id", None)
    if not study_id:
        return
    try:
        with transaction.atomic():
            study = AnalysisStudy.objects.select_for_update().filter(pk=study_id).first()
            if study is not None:
                refresh(study)
    except Exception:
        logger.exception("Refreshing study %s after run %s finished failed", study_id, getattr(run, "pk", None))


def reopen(study) -> None:
    """A run of a completed study was retried on its own: the study is running again."""
    AnalysisStudy.objects.filter(pk=study.pk, status=Status.COMPLETED).update(
        status=Status.RUNNING,
        completed_at=None,
        updated_at=timezone.now(),
    )


def retry_run(run, *, tools: list[str] | None = None):
    """Requeue one run of a study (all its retryable tools, or only *tools*); returns the study.

    Holds the study row lock like :func:`cancel` and :func:`retry_failed`
    (study row first, then the run row), so a concurrent study cancel
    either commits first (this retry is refused) or waits and then cancels
    the requeued run: a cancelled study never ends up with an active run.
    A completed study is running again. Raises :class:`StudyError` when the
    study's status allows no retry, ``ValueError`` from
    :func:`executor.retry` (run still active, nothing retryable).
    """
    with transaction.atomic():
        study = (
            AnalysisStudy.objects.select_for_update(of=("self",))
            .select_related("profile", "created_by")
            .get(pk=run.study_id)
        )
        if study.status not in TRANSITIONS["retry_failed"]:
            msg = (
                "The run belongs to a cancelled study."
                if study.status == Status.CANCELLED
                else f"Cannot retry a run of a study in status '{study.status}'."
            )
            raise StudyError(msg, code="invalid_state")
        check_procedure(study.plan, tools=tools)
        executor.retry(run, tools=tools)
        if study.status == Status.COMPLETED:
            study.status = Status.RUNNING
            study.completed_at = None
            study.save(update_fields=["status", "completed_at", "updated_at"])
    return study


def cancel(study):
    """Cancel every active run (cooperatively) and mark the study cancelled."""
    with transaction.atomic():
        study = _locked_row(study)
        _require(study, "cancel")
        for run in study.runs.filter(status__in=AnalysisRun.ACTIVE_STATUSES):
            executor.request_cancel(run)
        if launch_pending(study):
            # A launch job still submitting stops at its next target (it re-checks under this lock).
            study.preflight = {**study.preflight, "launch": {**launch_state(study), "status": "cancelled"}}
        study.status = Status.CANCELLED
        study.completed_at = timezone.now()
        study.save(update_fields=["status", "completed_at", "preflight", "updated_at"])
    return study


def retry_failed(study) -> dict[str, Any]:
    """Requeue the failed/partial/cancelled runs of a running or completed study.

    Returns ``{"retried": [run ids], "skipped": [{run_id, reason}]}`` (a run
    with nothing retryable, e.g. every tool not applicable, is skipped).
    """
    retried: list[str] = []
    skipped: list[dict[str, str]] = []
    with transaction.atomic():
        study = _locked_row(study)
        _require(study, "retry_failed")
        check_procedure(study.plan)
        for run in study.runs.filter(status__in=RETRYABLE_RUN_STATUSES).order_by("created_at", "id"):
            try:
                executor.retry(run)
            except ValueError as exc:
                skipped.append({"run_id": str(run.pk), "reason": str(exc)})
                continue
            retried.append(str(run.pk))
        if retried and study.status == Status.COMPLETED:
            study.status = Status.RUNNING
            study.completed_at = None
            study.save(update_fields=["status", "completed_at", "updated_at"])
    return {"retried": retried, "skipped": skipped}


def _stale_seconds() -> int:
    return int(getattr(settings, "ANALYSIS_STALE_SECONDS", 180))


def cost_of(usage: Any) -> float:
    """``usage["cost_usd"]`` as a float (0.0 when absent; cost is an amount spent, not a measurement)."""
    if not isinstance(usage, dict):
        return 0.0
    value = usage.get("cost_usd")
    if isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value):
        return float(value)
    return 0.0


def planned_tools(plan: dict[str, Any]) -> list[str]:
    """Tool slugs of a frozen plan in execution order (AI reviewer last)."""
    tools = [t["slug"] for t in (plan or {}).get("tools", []) if isinstance(t, dict) and t.get("slug")]
    reviewer = (plan or {}).get("reviewer") or {}
    if reviewer.get("enabled"):
        tools.append(reviewer.get("tool_slug") or "ai_review")
    return tools


def progress(study) -> dict[str, Any]:
    """Targets x tools status matrix with counts, cost so far and stale/queue hints."""
    study = refresh(study)
    now = timezone.now()
    tools = planned_tools(study.plan)
    # Tolerant here (resolve_design never raises): progress must render even
    # if the outcome catalogue changed since the design was validated.
    group_by = report_mod.resolve_design(study.analysis_design)[0]["group_by"]
    # Polled every few seconds: never load plans, manifests or measurements here.
    runs = list(study.runs.exclude(purpose=AnalysisRun.Purpose.CANARY).only(*PROGRESS_RUN_FIELDS))
    run_ids = [r.id for r in runs]
    tool_status: dict[Any, dict[str, dict[str, str]]] = {}
    tool_counts: dict[str, Counter] = {slug: Counter() for slug in tools}
    cost_by_run: dict[Any, float] = {}
    # Runs whose spend so far is a lower bound: a replicate without a recorded cost, one
    # flagged cost_complete false, or a replaced attempt whose spend is unknown.
    cost_partial: set[Any] = set()
    for row in ToolResult.objects.filter(run_id__in=run_ids).values(
        "run_id",
        "tool_slug",
        "status",
        "failure_reason",
        "summary",
    ):
        tool_status.setdefault(row["run_id"], {})[row["tool_slug"]] = {
            "status": row["status"],
            "failure_reason": row["failure_reason"],
        }
        tool_counts.setdefault(row["tool_slug"], Counter())[row["status"]] += 1
        summary = row["summary"] if isinstance(row["summary"], dict) else {}
        if summary.get("prior_attempts"):
            # A retry deletes the replaced replicates; their spend lives on in the summary.
            prior = summary.get("prior_attempts_cost_usd")
            cost_by_run[row["run_id"]] = cost_by_run.get(row["run_id"], 0.0) + cost_of({"cost_usd": prior})
            if prior is None or summary.get("prior_attempts_cost_unknown"):
                cost_partial.add(row["run_id"])
    for run_id, usage in ReviewSample.objects.filter(result__run_id__in=run_ids).values_list(
        "result__run_id",
        "usage",
    ):
        cost_by_run[run_id] = cost_by_run.get(run_id, 0.0) + cost_of(usage)
        spent = usage if isinstance(usage, dict) else {}
        if not isinstance(spent.get("cost_usd"), (int, float)) or spent.get("cost_complete") is False:
            cost_partial.add(run_id)

    stale_after = _stale_seconds()
    rows: list[dict[str, Any]] = []
    stale_ids: list[str] = []
    for run in runs:
        meta = run.target_meta or {}
        stale = bool(
            run.status == AnalysisRun.Status.RUNNING
            and run.heartbeat_at is not None
            and (now - run.heartbeat_at).total_seconds() > stale_after,
        )
        if stale:
            stale_ids.append(str(run.id))
        rows.append(
            {
                "run_id": str(run.id),
                "job_id": str(run.generation_job_id) if run.generation_job_id else meta.get("job_id"),
                "label": preflight_mod.target_label(meta),
                "group": preflight_mod.group_label(meta, group_by),
                "app_slug": meta.get("app_slug") or "",
                "model_slug": meta.get("model_slug") or "",
                "status": run.status,
                "phase": run.phase,
                "is_complete": run.is_complete,
                "attempt": run.attempt,
                "cancel_requested": run.cancel_requested,
                "stale": stale,
                "heartbeat_at": run.heartbeat_at,
                "started_at": run.started_at,
                "completed_at": run.completed_at,
                "duration_seconds": run.duration_seconds,
                "cost_usd": round(cost_by_run.get(run.id, 0.0), 6),
                "cost_complete": run.id not in cost_partial,
                "error_message": (run.error_message or "")[:500],
                "tools": {slug: tool_status.get(run.id, {}).get(slug, {"status": "missing"}) for slug in tools},
            },
        )
    rows.sort(key=lambda r: (r["group"], r["app_slug"], r["label"], r["run_id"]))

    preflight = study.preflight or {}
    launch_info = launch_state(study)
    not_launched = [dict(item, status="not_launched") for item in launch_info.get("skipped", [])]
    by_status = Counter(r["status"] for r in rows)
    run_counts = {s: by_status.get(s, 0) for s in AnalysisRun.Status.values}
    terminal = sum(run_counts[s] for s in AnalysisRun.TERMINAL_STATUSES)
    active = sum(run_counts[s] for s in AnalysisRun.ACTIVE_STATUSES)
    targets = preflight.get("targets", [])
    eligible = sum(1 for t in targets if t.get("eligible"))
    durations = [r["duration_seconds"] for r in rows if r["duration_seconds"] and r["status"] != "cancelled"]
    max_concurrent = int(getattr(settings, "ANALYSIS_MAX_CONCURRENT_RUNS", 2)) or 1
    eta = None
    if durations and active:
        eta = round(sum(durations) / len(durations) * active / max_concurrent, 1)
    queued_global = AnalysisRun.objects.filter(status=AnalysisRun.Status.QUEUED)
    first_queued = min((r.created_at for r in runs if r.status == AnalysisRun.Status.QUEUED), default=None)
    queued_ahead = 0
    if first_queued is not None:
        queued_ahead = queued_global.filter(created_at__lt=first_queued).exclude(study=study).count()
    return json_safe(
        {
            "study_id": str(study.pk),
            "status": study.status,
            "generated_at": now,
            "group_by": group_by,
            "tools": tools,
            "launch": {
                "status": launch_info.get("status") or ("submitted" if launch_info else None),
                "planned": launch_info.get("planned", launch_info.get("eligible_targets")),
                "submitted": len(rows),
                "skipped": len(not_launched),
                "pending": launch_pending(study),
                "attempts": launch_info.get("attempts"),
                "requested_at": launch_info.get("requested_at"),
                "finished_at": launch_info.get("finished_at"),
                "error": launch_info.get("error") or None,
            },
            "counts": {
                "targets": len(targets),
                "eligible": eligible,
                "excluded": len(targets) - eligible,
                "planned": launch_info.get("planned", launch_info.get("eligible_targets", eligible)),
                "submitted": len(rows),
                "not_launched": len(not_launched),
                "runs": run_counts,
                "terminal": terminal,
                "active": active,
                "complete": sum(1 for r in rows if r["is_complete"]),
            },
            "progress": round(terminal / len(rows), 4) if rows else None,
            "tool_counts": {slug: dict(counter) for slug, counter in tool_counts.items()},
            "rows": rows,
            "not_launched": not_launched,
            "cost": {
                "so_far_usd": round(sum(cost_by_run.values()), 6),
                # False: so_far_usd is a lower bound (some replicate's or replaced attempt's spend is unknown).
                "complete": not cost_partial,
                "runs_with_unknown_cost": len(cost_partial),
                "estimate_usd": (preflight.get("estimates") or {}).get("ai_cost_usd"),
            },
            "timing": {
                "launched_at": study.launched_at,
                "elapsed_seconds": round((now - study.launched_at).total_seconds(), 1) if study.launched_at else None,
                "eta_seconds": eta,
            },
            "stale": {"count": len(stale_ids), "run_ids": stale_ids, "threshold_seconds": stale_after},
            "queue": {
                "max_concurrent_runs": max_concurrent,
                "running_global": AnalysisRun.objects.filter(status=AnalysisRun.Status.RUNNING).count(),
                "queued_global": queued_global.count(),
                "queued_ahead": queued_ahead,
            },
        },
    )


