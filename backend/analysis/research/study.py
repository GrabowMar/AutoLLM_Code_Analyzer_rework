def _uuid_str(value: Any, path: str, errors: dict[str, str]) -> str | None:
    try:
        return str(uuid.UUID(str(value)))
    except (TypeError, ValueError, AttributeError):
        errors[path] = "must be a UUID"
        return None


def _str_list(value: Any, path: str, errors: dict[str, str], *, max_items: int = 500) -> list[str]:
    if value is None:
        return []
    if not isinstance(value, list) or not all(isinstance(v, str) and v.strip() for v in value):
        errors[path] = "must be a list of non-empty strings"
        return []
    if len(value) > max_items:
        errors[path] = f"at most {max_items} items"
        return []
    return sorted({v.strip() for v in value})


def _int_list(value: Any, path: str, errors: dict[str, str], *, max_items: int = 500) -> list[int]:
    if value is None:
        return []
    if not isinstance(value, list) or not all(isinstance(v, int) and not isinstance(v, bool) for v in value):
        errors[path] = "must be a list of integers"
        return []
    if len(value) > max_items:
        errors[path] = f"at most {max_items} items"
        return []
    return sorted(set(value))


def _iso_bound(value: Any, path: str, errors: dict[str, str]) -> str | None:
    if value in (None, ""):
        return None
    if isinstance(value, str):
        try:
            dt = parse_datetime(value)
            if dt is None and (d := parse_date(value)) is not None:
                dt = datetime.combine(d, time.min)
        except ValueError:
            dt = None
        if dt is not None:
            if timezone.is_naive(dt):
                dt = timezone.make_aware(dt)
            return dt.isoformat()
    errors[path] = "must be an ISO date or datetime"
    return None


def _validate_filters(raw: Any, errors: dict[str, str]) -> dict[str, Any]:
    from backend.generation.models import GenerationJob

    base = "target_spec.filters"
    if raw in (None, {}):
        return {}
    if not isinstance(raw, dict):
        errors[base] = "must be an object"
        return {}
    out: dict[str, Any] = {}
    for key in raw:
        if key not in FILTER_KEYS:
            errors[f"{base}.{key}"] = "unknown filter"
    model_ids = raw.get("model_ids")
    if model_ids is not None:
        if not isinstance(model_ids, list) or not all(
            (isinstance(v, int) and not isinstance(v, bool)) or (isinstance(v, str) and v.strip()) for v in model_ids
        ):
            errors[f"{base}.model_ids"] = "must be a list of catalog ids (int) or model slugs (str)"
        elif model_ids:
            out["model_ids"] = sorted(set(model_ids), key=lambda v: (isinstance(v, str), str(v)))
    modes = _str_list(raw.get("modes"), f"{base}.modes", errors)
    if bad_modes := [m for m in modes if m not in GenerationJob.Mode.values]:
        errors[f"{base}.modes"] = f"unknown mode(s): {', '.join(bad_modes)}"
    elif modes:
        out["modes"] = modes
    for key in ("harnesses", "stacks", "app_slugs"):
        if values := _str_list(raw.get(key), f"{base}.{key}", errors):
            out[key] = values
    for key in ("created_after", "created_before"):
        if (bound := _iso_bound(raw.get(key), f"{base}.{key}", errors)) is not None:
            out[key] = bound
    if raw.get("status") not in (None, "", GenerationJob.Status.COMPLETED):
        errors[f"{base}.status"] = "only completed jobs can be analysed"
    return out


def validate_target_spec(spec: Any) -> dict[str, Any]:
    """Normalize a target spec; raises ConfigError with ``target_spec.*`` field paths."""
    if not isinstance(spec, dict):
        raise ConfigError({"target_spec": "must be an object"})
    errors: dict[str, str] = {}
    allowed = {"kind", "experiment_id", "condition_ids", "app_slugs", "batch_id", "job_ids", "filters"}
    for key in spec:
        if key not in allowed:
            errors[f"target_spec.{key}"] = "unknown field"
    kind = spec.get("kind")
    if kind not in KINDS:
        errors["target_spec.kind"] = f"must be one of {', '.join(KINDS)}"
    out: dict[str, Any] = {"kind": kind}
    if kind == "experiment":
        if spec.get("experiment_id") in (None, ""):
            errors["target_spec.experiment_id"] = "required for kind=experiment"
        else:
            out["experiment_id"] = _uuid_str(spec.get("experiment_id"), "target_spec.experiment_id", errors)
        if condition_ids := _int_list(spec.get("condition_ids"), "target_spec.condition_ids", errors):
            out["condition_ids"] = condition_ids
        if app_slugs := _str_list(spec.get("app_slugs"), "target_spec.app_slugs", errors):
            out["app_slugs"] = app_slugs
    else:
        for key in ("experiment_id", "condition_ids", "app_slugs"):
            if spec.get(key) not in (None, [], ""):
                errors[f"target_spec.{key}"] = "only valid for kind=experiment"
    if kind == "batch":
        if spec.get("batch_id") in (None, ""):
            errors["target_spec.batch_id"] = "required for kind=batch"
        else:
            out["batch_id"] = _uuid_str(spec.get("batch_id"), "target_spec.batch_id", errors)
    elif spec.get("batch_id") not in (None, ""):
        errors["target_spec.batch_id"] = "only valid for kind=batch"
    if kind == "jobs":
        raw_ids = spec.get("job_ids")
        if not isinstance(raw_ids, list) or not raw_ids:
            errors["target_spec.job_ids"] = "a non-empty list of job ids is required for kind=jobs"
        elif len(raw_ids) > MAX_JOB_IDS:
            errors["target_spec.job_ids"] = f"at most {MAX_JOB_IDS} jobs"
        else:
            ids = []
            for i, raw in enumerate(raw_ids):
                if (value := _uuid_str(raw, f"target_spec.job_ids.{i}", errors)) is not None:
                    ids.append(value)
            out["job_ids"] = sorted(set(ids))
    elif spec.get("job_ids") not in (None, []):
        errors["target_spec.job_ids"] = "only valid for kind=jobs"
    if filters := _validate_filters(spec.get("filters"), errors):
        out["filters"] = filters
    if errors:
        raise ConfigError(errors)
    return out


def validate_exclusion_rules(rules: Any) -> dict[str, Any]:
    """Defaults merged with *rules* (unknown keys rejected, types checked)."""
    defaults = dict(sample_mod.DEFAULT_EXCLUSION_RULES)
    if rules in (None, {}):
        return defaults
    if not isinstance(rules, dict):
        raise ConfigError({"exclusion_rules": "must be an object"})
    errors: dict[str, str] = {}
    out = dict(defaults)
    for key, value in rules.items():
        path = f"exclusion_rules.{key}"
        if key not in defaults:
            errors[path] = "unknown rule"
            continue
        default = defaults[key]
        if isinstance(default, bool):
            if not isinstance(value, bool):
                errors[path] = "must be a boolean"
                continue
        elif isinstance(default, int) and (isinstance(value, bool) or not isinstance(value, int) or value < 0):
            errors[path] = "must be a non-negative integer"
            continue
        out[key] = value
    if errors:
        raise ConfigError(errors)
    return out


